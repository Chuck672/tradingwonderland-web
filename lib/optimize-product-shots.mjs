/**
 * Crop the OS title bar off the PiTradingAgent screenshots and write
 * near-lossless AVIF, WebP, and JPEG at the widths the homepage srcset uses.
 *
 * Source PNGs are the full-window captures (they still show the "IDE" title).
 * Pass them with SOURCE_DIR. Outputs land in public/product/.
 *
 *   SOURCE_DIR=/path/to/pngs node lib/optimize-product-shots.mjs
 */
import { statSync } from "node:fs";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SOURCE_DIR = process.env.SOURCE_DIR;
if (!SOURCE_DIR) {
  console.error("Set SOURCE_DIR to the folder of source PNGs.");
  process.exit(1);
}

const OUT_DIR = path.join(process.cwd(), "public/product");
const WIDTHS = [1280, 2400];

/** Upload filename → slide id. Order is the carousel order. */
const SLIDES = [
  ["ai", "Screenshot_2026-10-23_215019_3638.png"],
  ["chart", "Screenshot_2026-10-23_215131_edb5.png"],
  ["indicators", "Screenshot_2026-10-23_215217_0fe5.png"],
  ["range", "Screenshot_2026-10-23_215316_6212.png"],
  ["calendar", "Screenshot_2026-10-23_215422_cc57.png"],
  ["alerts", "Screenshot_2026-10-23_215731_9adb.png"],
  ["ticket", "Screenshot_2026-10-23_215849_b446.png"],
];

const RETIRED = [
  "ai-agent.png",
  "alerts.png",
  "chart-multitf.png",
  "hero-ai.png",
  "indicator-a.png",
  "indicator-b.png",
  "trading-risk.png",
];

function findTitleBarHeight(data, width, height, channels) {
  let seenGray = false;
  for (let y = 0; y < Math.min(height, 240); y++) {
    let r = 0;
    let g = 0;
    let b = 0;
    let n = 0;
    const samples = [];
    for (let x = 0; x < width; x += 8) {
      const i = (y * width + x) * channels;
      const sample = [data[i], data[i + 1], data[i + 2]];
      samples.push(sample);
      r += sample[0];
      g += sample[1];
      b += sample[2];
      n += 1;
    }
    r /= n;
    g /= n;
    b /= n;
    let variance = 0;
    for (const [rr, gg, bb] of samples) {
      variance += (rr - r) ** 2 + (gg - g) ** 2 + (bb - b) ** 2;
    }
    variance /= samples.length;
    const gray = Math.abs(r - g) < 12 && Math.abs(g - b) < 12 && r > 22 && r < 60;
    const appChrome = r < 20 && g < 26 && b < 36 && variance < 80;
    if (gray) seenGray = true;
    if (seenGray && appChrome) return y;
  }
  throw new Error("Could not find the OS title bar. Refusing to ship an uncropped frame.");
}

async function encodeSlide(id, file) {
  const sourcePath = path.join(SOURCE_DIR, file);
  const input = sharp(sourcePath).ensureAlpha();
  const { data, info } = await input.raw().toBuffer({ resolveWithObject: true });
  const cropY = findTitleBarHeight(data, info.width, info.height, info.channels);
  const croppedHeight = info.height - cropY;
  const cropped = sharp(sourcePath).extract({
    left: 0,
    top: cropY,
    width: info.width,
    height: croppedHeight,
  }).removeAlpha();

  const full = await cropped.png().toBuffer();
  const master = await sharp(full)
    .resize({ width: WIDTHS[WIDTHS.length - 1], kernel: "lanczos3", withoutEnlargement: true })
    .toBuffer();
  const masterMeta = await sharp(master).metadata();
  const sourceBytes = statSync(sourcePath).size;
  const outputs = [];

  for (const width of WIDTHS) {
    const resized = width === masterMeta.width
      ? master
      : await sharp(full).resize({ width, kernel: "lanczos3", withoutEnlargement: true }).toBuffer();

    const avif = await sharp(resized).avif({
      quality: 80,
      effort: 7,
      chromaSubsampling: "4:4:4",
    }).toBuffer();
    const webp = await sharp(resized).webp({
      nearLossless: true,
      quality: 30,
      effort: 6,
    }).toBuffer();
    const jpeg = await sharp(resized).jpeg({
      quality: 85,
      mozjpeg: true,
      chromaSubsampling: "4:4:4",
    }).toBuffer();

    const written = [
      [`${id}-${width}.avif`, avif],
      [`${id}-${width}.webp`, webp],
      [`${id}-${width}.jpg`, jpeg],
    ];
    for (const [name, buf] of written) {
      await writeFile(path.join(OUT_DIR, name), buf);
      outputs.push({ file: name, bytes: buf.length });
    }
  }

  return {
    id,
    sourceFile: file,
    sourceBytes,
    cropY,
    width: masterMeta.width,
    height: masterMeta.height,
    outputs,
  };
}

const existing = await readdir(OUT_DIR).catch(() => []);
await mkdir(OUT_DIR, { recursive: true });
for (const name of existing) {
  if (RETIRED.includes(name) || /^(ai|chart|indicators|range|calendar|alerts|ticket)-\d+\.(avif|webp|jpg)$/.test(name)) {
    await rm(path.join(OUT_DIR, name));
  }
}

const results = [];
for (const [id, file] of SLIDES) {
  process.stderr.write(`encoding ${id}…\n`);
  results.push(await encodeSlide(id, file));
}

const meta = {};
for (const result of results) meta[result.id] = { width: result.width, height: result.height };

const metaSource = `/* Generated by lib/optimize-product-shots.mjs. Do not edit by hand. */\nexport const productShotMeta = ${JSON.stringify(meta, null, 2)} as const;\n\nexport const productShotWidths = [1280, 2400] as const;\n`;
await writeFile(path.join(process.cwd(), "lib/product-shot-meta.ts"), metaSource);

const report = {
  note: "AVIF quality 80, 4:4:4, effort 7. WebP near-lossless quality 30. JPEG mozjpeg quality 85, 4:4:4. Title bar cropped before resize.",
  slides: results,
};
console.log(JSON.stringify(report, null, 2));
