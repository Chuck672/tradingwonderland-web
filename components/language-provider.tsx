const LanguageContext = createContext<LanguageContextType | undefined>(undefined);
const LANGUAGE_STORAGE_KEY = "qll-lang";

export function fillTemplate(template: string, values: Record<string, string>) {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => values[name] ?? "");
}

export function translateError(
  t: (key: string) => string,
  prefix: "auth.err" | "api.err",
  code: string | null | undefined,
) {
  const fallback = prefix === "auth.err" ? "auth.err.generic" : "api.err.server";
  if (!code) return t(fallback);
  const key = `${prefix}.${code}`;
  const value = t(key);
  return value === key ? t(fallback) : value;
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    try {
      const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
      if (stored === "en" || stored === "zh") {
        setLanguageState(stored);
      }
    } catch {
      // Storage can be blocked. First paint stays English.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  }, [language]);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    } catch {
      // The choice still applies for this visit.
    }
  };

  const t = (key: string) => {
    return translations[language][key as keyof typeof translations["zh"]] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
}
